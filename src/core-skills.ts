/** Build AssistantSkill objects from the core seeds (used once at first load). */
export function coreSkillsAsAssistantSkills(): AssistantSkill[] {
  const nowIso = new Date().toISOString();
  return CORE_SKILLS.map((seed, i) => ({
    id: `core-skill-${i + 1}`,
    name: seed.name,
    description: seed.description,
    instructions: seed.instructions,
    active: true,
    createdAt: nowIso,
    updatedAt: nowIso,
    versions: [{ version: 1, ...seed, savedAt: nowIso }],
    core: true,
  }));
}
